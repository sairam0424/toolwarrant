// Seventh review (canary-5, D17 j): emit --out refused a symbolic link,
// directory, device, socket or named pipe but accepted any regular file, the
// catalog database included: "emit --out <the --db path>" opened the catalog,
// staged the YAML next to it and renamed it over the database while the store
// still held the old inode, recorded the processor address into the unlinked
// inode and exited 0 with "wrote <db>"; every later command then refused the
// file ("file is not a database") and the only recovery was a backup. The
// database, its -wal and -shm siblings and the gateway binary are now refused
// by canonical path and by identity (the siblings whether or not they exist at
// that moment: SQLite removes them on a clean close, and a configuration
// written into that slot is deleted by the next open), and so is any existing
// regular file whose first lines are not emit's header, each as a usage error
// naming the fix; a file emit wrote, and a file the gateway rewrote keeping
// the header lines, are still replaced.
func TestEmitRefusesToReplaceTheCatalogOrAFileItDidNotWrite(t *testing.T) {
	t.Parallel()
	c, _ := fixture(t)
	c.approve("alice", "s1", "echo", c.tool("s1", "echo").Pending)
	before, err := os.ReadFile(c.db)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(before), "SQLite format 3") {
		t.Fatalf("the fixture's database is not a SQLite file: %q", before[:16])
	}
	dir := filepath.Dir(c.db)
	// Built by concatenation, not filepath.Join, which would clean the dots
	// away and leave the same spelling as c.db (eighth review).
	relative := dir + string(filepath.Separator) + ".." + string(filepath.Separator) + filepath.Base(dir) + string(filepath.Separator) + filepath.Base(c.db)
	if relative == c.db {
		t.Fatalf("the relative spelling collapsed to the database path %q", relative)
	}
	gateway, _ := fakeGateway(t, t.TempDir(), "gateway-ok", 0, "")
	for name, tc := range map[string]struct {
		out, what string
		args      []string
		plant     bool // write a stand-in at out first; SQLite removes the siblings on a clean close
	}{
		"the database":                    {c.db, "the catalog database (--db)", nil, false},
		"a relative spelling":             {relative, "the catalog database (--db)", nil, false},
		"the -wal sibling, present":       {c.db + walSuffix, "the catalog's write-ahead log", nil, true},
		"the -shm sibling, present":       {c.db + shmSuffix, "the catalog's shared-memory index", nil, true},
		"the -wal sibling, absent":        {c.db + walSuffix, "the catalog's write-ahead log", nil, false},
		"the -shm sibling, absent":        {c.db + shmSuffix, "the catalog's shared-memory index", nil, false},
		"a relative spelling of the -wal": {relative + walSuffix, "the catalog's write-ahead log", nil, false},
		"the gateway binary":              {gateway, "the gateway binary (--gateway-binary)", []string{"--gateway-binary", gateway}, false},
	} {
		if tc.plant {
			if err := os.WriteFile(tc.out, []byte("sqlite sibling"), 0o600); err != nil {
				t.Fatal(err)
			}
		}
		r := c.fail(exitUsage, append([]string{"emit", "--out", tc.out}, tc.args...)...)
		wantContains(t, name, r.stderr, "--out "+tc.out+" is "+tc.what+"; emit would replace it with the gateway configuration, so name another file")
		wantNotContains(t, name, r.stdout, "wrote ")
		if tc.plant {
			if err := os.Remove(tc.out); err != nil {
				t.Fatal(err)
			}
		} else if strings.HasSuffix(tc.out, walSuffix) || strings.HasSuffix(tc.out, shmSuffix) {
			if _, err := os.Lstat(tc.out); !errors.Is(err, fs.ErrNotExist) {
				t.Errorf("%s: a file exists at the sibling path after the refused emit (%v)", name, err)
			}
		}
	}
	after, err := os.ReadFile(c.db)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(after), "SQLite format 3") || len(after) != len(before) {
		t.Fatalf("the database was touched: %d bytes, %q", len(after), after[:16])
	}
	if got := readFile(t, gateway); !strings.HasPrefix(got, "#!/bin/sh") {
		t.Errorf("the gateway binary was touched: %q", got)
	}
	wantContains(t, "list still works", c.ok("list"), "echo")

	// A regular file that is not emit's: refused, untouched, exit 2.
	foreign := filepath.Join(t.TempDir(), "gateway.yaml")
	for name, content := range map[string]string{"text": "routes: []\n", "empty": "", "header without the hash line": "# Generated by toolwarrant. Do not edit by hand: changes are overwritten\n"} {
		if err := os.WriteFile(foreign, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
		r := c.fail(exitUsage, "emit", "--out", foreign)
		wantContains(t, name, r.stderr, "--out "+foreign+" exists and its first lines are not the header emit writes, so it is not a file emit wrote; emit replaces only its own files (a file the gateway rewrote keeps the header and is replaced), so move it away or name another file")
		if got := readFile(t, foreign); got != content {
			t.Errorf("%s: the refused emit touched the file: %q", name, got)
		}
	}
	if err := os.Remove(foreign); err != nil {
		t.Fatal(err)
	}

	// A file emit wrote is replaced, and so is one the gateway rewrote with
	// the header lines kept and the body changed (what the admin API does to
	// the watched file), which is the documented re-emit after CONFIG-EDITED.
	out := filepath.Join(t.TempDir(), "gateway.yaml")
	c.ok("emit", "--out", out)
	c.ok("emit", "--out", out)
	written := readFile(t, out)
	hash, ok := emit.Verify([]byte(written))
	if !ok {
		t.Fatal("the written file does not verify")
	}
	i := strings.Index(written, "# toolwarrant-sha256: "+hash+"\n")
	if i < 0 {
		t.Fatal("no hash line in the emitted file")
	}
	rewritten := written[:i+len("# toolwarrant-sha256: "+hash+"\n")] + "routes: []\n"
	if _, ok := emit.Verify([]byte(rewritten)); ok {
		t.Fatal("the rewritten file still verifies; the test does not model a rewrite")
	}
	if err := os.WriteFile(out, []byte(rewritten), 0o600); err != nil {
		t.Fatal(err)
	}
	wantContains(t, "re-emit over a rewritten file", c.ok("emit", "--out", out), "wrote "+out)
	if got := readFile(t, out); got != written {
		t.Errorf("the re-emit did not restore the emitted bytes")
	}
}

// Seventh review (catalog-chain-4, D17 c), the CLI half: the catalog's Servers
// view hands out each server's processor address anchored to the verified
// server.processor_set entry and answers ErrCorrupt when the column disagrees
// with it; emit used to adopt a rewritten column silently, write the forged
// address into the gateway configuration, print no change line and append no
// entry, so the gateway would have dialled the forger's processor for every
// hook. emit now writes nothing on ErrCorrupt and exits 1 with the catalog's
// advice, and every address it writes that differs from the recorded one is
// printed as new or changed (TestEmitWritesTheGatewayConfigAtomically pins
// the changed-from line for an override).
func TestEmitRefusesACatalogWhoseProcessorAddressIsNotTheOneTheChainRecords(t *testing.T) {
	t.Parallel()
	c, _ := fixture(t)
	c.approve("alice", "s1", "echo", c.tool("s1", "echo").Pending)
	out := filepath.Join(t.TempDir(), "gateway.yaml")
	wantContains(t, "first emit", c.ok("emit", "--out", out), "processor address of server s1 is new: 127.0.0.1:9001")
	written := readFile(t, out)
	execSQL(t, c.db, `UPDATE servers SET processor_addr = '127.0.0.1:9999' WHERE name = 's1'`)

	r := c.fail(exitFailure, "emit", "--out", out)
	wantContains(t, "stderr", r.stderr, adviceCorrupt)
	wantNotContains(t, "stdout", r.stdout, "wrote ", "127.0.0.1:9999")
	if got := readFile(t, out); got != written {
		t.Errorf("the refused emit replaced the file:\n%s", got)
	}
	// The forged address, not a bare "9999": the file carries a sha256 header
	// whose hex digits can spell any four-digit run (one in about a thousand
	// emits did, in a CI run on 2026-10-14).
	wantNotContains(t, "file", readFile(t, out), "127.0.0.1:9999")
	fresh := filepath.Join(t.TempDir(), "fresh.yaml")
	c.fail(exitFailure, "emit", "--out", fresh)
	if _, err := os.Stat(fresh); !os.IsNotExist(err) {
		t.Errorf("the refused emit wrote a file: %v", err)
	}
	if entries := c.processorSetEntries(); len(entries) != 1 {
		t.Errorf("the refused emit changed the audit log: %+v", entries)
	}
}
