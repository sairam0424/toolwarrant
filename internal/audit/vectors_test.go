// Spec: "e.Hash to the lower-case hex SHA-256 of the RFC 8785 canonical JSON
// of the entry WITHOUT the hash field, with keys seq, ts, actor, actor_type,
// event, subject, before_hash, after_hash, detail, prev_hash."
func TestSeal_MatchesTheIndependentPythonReference(t *testing.T) {
	var sealed []audit.Entry
	for _, v := range sealVectors() {
		prev := audit.Entry{}
		if v.prevIndex >= 0 {
			prev = sealed[v.prevIndex]
		}
		got, err := audit.Seal(prev, v.entry)
		if err != nil {
			t.Fatalf("%s: Seal: %v", v.name, err)
		}
		if got.PrevHash != v.wantPrev {
			t.Errorf("%s: PrevHash = %q, want %q", v.name, got.PrevHash, v.wantPrev)
		}
		if got.Hash != v.wantHash {
			t.Errorf("%s: Hash = %q, want %q (reference)", v.name, got.Hash, v.wantHash)
		}
		sealed = append(sealed, got)
	}
}

// The first four vectors chain to each other, so sealing them in order gives a
// log whose links and hashes were all computed outside Go.
func TestVerify_AcceptsTheReferenceChain(t *testing.T) {
	var chain []audit.Entry
	for _, v := range sealVectors()[:4] {
		prev := audit.Entry{}
		if len(chain) > 0 {
			prev = chain[len(chain)-1]
		}
		sealedEntry, err := audit.Seal(prev, v.entry)
		if err != nil {
			t.Fatalf("%s: Seal: %v", v.name, err)
		}
		chain = append(chain, sealedEntry)
	}
	if err := audit.Verify(chain); err != nil {
		t.Fatalf("Verify(reference chain): %v", err)
	}
	wantHead := sealVectors()[3].wantHash
	if got := audit.Head(chain); got != wantHead {
		t.Errorf("Head = %q, want %q", got, wantHead)
	}
}

// Verify must recompute hashes itself: a chain built by hand from the
// reference values (not by Seal) verifies too.
func TestVerify_AcceptsAChainBuiltFromReferenceValues(t *testing.T) {
	var chain []audit.Entry
	for _, v := range sealVectors()[:4] {
		e := v.entry
		e.PrevHash, e.Hash = v.wantPrev, v.wantHash
		chain = append(chain, e)
	}
	if err := audit.Verify(chain); err != nil {
		t.Fatalf("Verify(chain built from reference hashes): %v", err)
	}
}
